import numpy as np

# ---------- 12. Хоёр хэмжээст массивын мөр, баганын нийлбэр ----------
A = np.array([[12, 15, 18],
              [20, 25, 30],
              [10, 14, 16]])

print("12-р бодлого")
print("Мөр бүрийн нийлбэр:", A.sum(axis=1))
print("Багана бүрийн дундаж:", A.mean(axis=0))
print("Хамгийн их элемент:", A.max())

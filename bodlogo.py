# ---------- 13. Нэг дэлгүүрийн 7 хоногийн борлуулалт ----------
sales = np.array([250, 320, 180, 400, 350, 500, 280])
                   
print("\n13-р бодлого")
print("Нийт борлуулалт:", sales.sum())
print("Өдрийн дундаж борлуулалт:", sales.mean())

best_day = np.argmax(sales)   # хамгийн их борлуулалттай өдрийн индекс
print("Хамгийн их борлуулалттай өдөр:", best_day + 1, "-р өдөр (", sales[best_day], ")")

print("300 мянгаас дээш борлуулалттай өдрийн тоо:", np.sum(sales > 300))

new_sales = sales * 1.10      # бүгдийг 10%-иар нэмэгдүүлнэ
print("10%-иар нэмэгдүүлсэн шинэ массив:", new_sales)

